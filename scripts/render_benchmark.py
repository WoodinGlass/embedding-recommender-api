#!/usr/bin/env python3
"""Render the FAISS benchmark JSON as Markdown (ADR-0011).

    python scripts/render_benchmark.py
    python scripts/render_benchmark.py --input docs/faiss-benchmark.json \
        --output docs/faiss-benchmark.md

The generated file is never edited by hand. The README table cites the
JSON; this Markdown is the human-readable companion to it. If they
disagree, the JSON is authoritative.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]


def _human_bytes(n: int) -> str:
    if n <= 0:
        return "unknown"
    for unit in ("B", "KiB", "MiB", "GiB"):
        if n < 1024:
            return f"{n:.1f} {unit}"
        n /= 1024  # type: ignore[assignment]
    return f"{n:.1f} TiB"


def _fmt(v: Any) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def render(doc: dict[str, Any]) -> str:
    """Return the Markdown representation of ``doc``."""
    env = doc["environment"]
    inp = doc["inputs"]
    params = doc["parameters"]

    lines: list[str] = []
    lines.append("# FAISS benchmark")
    lines.append("")
    lines.append(
        "Generated by `scripts/render_benchmark.py` from "
        "[`faiss-benchmark.json`](faiss-benchmark.json). **Do not edit by "
        "hand.** The JSON is the source of truth (ADR-0011)."
    )
    lines.append("")
    lines.append(f"- **Commit:** `{doc['commit']}`")
    lines.append(f"- **Run at:** {doc['created_at']}")
    lines.append(f"- **Run id:** `{inp['run_id']}`")
    lines.append(f"- **Model version:** `{inp['model_version']}`")
    lines.append(f"- **Golden set version:** `{inp['golden_set_version']}`")
    lines.append(f"- **Vectors:** {inp['vector_count']} (dim {inp['vector_dim']})")
    lines.append(f"- **k:** {inp['k']}")
    lines.append("")

    lines.append("## Environment")
    lines.append("")
    lines.append("| Field | Value |")
    lines.append("|---|---|")
    lines.append(f"| CPU | {env['cpu_model']} |")
    lines.append(f"| Logical cores | {env['cpu_count']} |")
    lines.append(f"| RAM | {_human_bytes(env['ram_bytes'])} |")
    lines.append(f"| OS | {env['os']} ({env['kernel']}) |")
    lines.append(f"| Python | {env['python_version']} |")
    lines.append(f"| NumPy | {env['numpy_version'] or 'unknown'} |")
    lines.append(f"| FAISS | {env['faiss_version'] or 'unknown'} |")
    lines.append(f"| Threads | {env['num_threads']} |")
    lines.append(f"| Seed | {env['seed']} |")
    lines.append("")

    lines.append("## Parameters")
    lines.append("")
    lines.append(f"- `hnsw_m = {params['hnsw_m']}`")
    lines.append(f"- `hnsw_ef_construction = {params['hnsw_ef_construction']}`")
    lines.append(f"- `ef_search` grid: {', '.join(str(x) for x in params['ef_search_grid'])}")
    lines.append(
        f"- Warmup: {params['warmup_queries']} queries, measured: "
        f"{params['measured_queries']} queries"
    )
    lines.append("")

    lines.append("## Exact kNN (numpy)")
    lines.append("")
    exact = doc["systems"]["exact_knn"]
    lines.append("| Metric | Value |")
    lines.append("|---|---|")
    for k, v in sorted(exact["metrics"].items()):
        lines.append(f"| {k} | {_fmt(v)} |")
    lines.append(f"| p50 latency | {exact['latency']['p50_ms']:.4f} ms |")
    lines.append(f"| p95 latency | {exact['latency']['p95_ms']:.4f} ms |")
    lines.append(f"| p99 latency | {exact['latency']['p99_ms']:.4f} ms |")
    lines.append(f"| QPS | {exact['qps']} |")
    lines.append("")

    lines.append("## FAISS HNSW — recall/latency curve")
    lines.append("")
    lines.append(
        "| ef_search | recall_at_k | ndcg_at_k | mrr | ANN fidelity | "
        "p50 (ms) | p95 (ms) | p99 (ms) | QPS |"
    )
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for _label, block in sorted(
        doc["systems"]["faiss_hnsw"].items(),
        key=lambda kv: kv[1]["ef_search"],
    ):
        m = block["metrics"]
        lat = block["latency"]
        lines.append(
            f"| {block['ef_search']} | {_fmt(m.get('recall_at_10'))} | "
            f"{_fmt(m.get('ndcg_at_10'))} | {_fmt(m.get('mrr'))} | "
            f"{_fmt(m.get('ann_recall_vs_exact'))} | "
            f"{lat['p50_ms']:.4f} | {lat['p95_ms']:.4f} | "
            f"{lat['p99_ms']:.4f} | {block['qps']} |"
        )
    lines.append("")
    first_faiss_block = next(iter(doc["systems"]["faiss_hnsw"].values()))
    lines.append(
        f"Index build time (one build, reused across the ef_search grid): "
        f"{first_faiss_block['index_build_time_s']:.2f} s."
    )
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    lines.append(doc["notes"])
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=pathlib.Path,
        default=REPO_ROOT / "docs" / "faiss-benchmark.json",
    )
    parser.add_argument(
        "--output",
        type=pathlib.Path,
        default=REPO_ROOT / "docs" / "faiss-benchmark.md",
    )
    args = parser.parse_args(argv)

    if not args.input.is_file():
        print(
            json.dumps(
                {
                    "event": "render.input_missing",
                    "path": str(args.input),
                    "hint": "run `python scripts/bench_faiss.py` first",
                }
            ),
            file=sys.stderr,
        )
        return 2

    try:
        doc = json.loads(args.input.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        print(
            json.dumps({"event": "render.invalid_json", "message": str(e)}),
            file=sys.stderr,
        )
        return 2

    text = render(doc)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(
        json.dumps(
            {
                "event": "render.written",
                "path": str(args.output),
                "bytes": len(text),
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
